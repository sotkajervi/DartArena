CREATE OR REPLACE FUNCTION public.apply_pentathlon_room_test(p_challenge_id uuid, p_expected_version bigint, p_action text, p_next jsonb)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare r public.pentathlon_room_tests%rowtype;v_user uuid:=auth.uid();v_slot integer;
  v_old jsonb;v_old_count integer;v_new_count integer;v_idx integer;v_changed integer:=0;v_owned_later integer;
  v_prev_entry jsonb;v_next_entry jsonb;v_other_slot integer;
begin
  if v_user is null then raise exception 'Authentication required';end if;
  select * into r from public.pentathlon_room_tests where challenge_id=p_challenge_id for update;
  if not found or v_user not in(r.player1_id,r.player2_id) then raise exception 'Pentathlon test not found';end if;
  if r.version<>p_expected_version then raise exception 'PENTATHLON_STALE_VERSION';end if;
  if r.match_id is not null and not exists(select 1 from public.matches where id=r.match_id and game_variant='pentathlon' and status='playing')
  then raise exception 'Pentathlon match is no longer active';end if;
  if p_action not in ('turn','advance','undo','correct') then raise exception 'Invalid Pentathlon action';end if;
  if jsonb_typeof(p_next)<>'object' or octet_length(p_next::text)>180000
    or p_next->'players' is distinct from r.state->'players'
    or p_next->'firstStarter' is distinct from r.state->'firstStarter'
    or p_next->'createdAt' is distinct from r.state->'createdAt'
    or p_next->>'version'<>'1'
    or (p_next->>'stageIndex')::integer not between 0 and 7
    or p_next->>'status' not in ('playing','review','finished')
    then raise exception 'Invalid Pentathlon state';end if;
  v_slot:=case when v_user=r.player1_id then 0 else 1 end;
  v_old:=r.state;
  if p_action='turn' then
    if v_old->>'status'<>'playing' or (v_old->'current'->>'turn')::integer<>v_slot
      or p_next->'stageIndex' is distinct from v_old->'stageIndex'
      or p_next->'summaries' is distinct from v_old->'summaries'
         and p_next->>'status'<>'review'
      then raise exception 'Not your turn';end if;
    v_old_count:=jsonb_array_length(coalesce(v_old->'current'->'entries','[]'::jsonb));
    v_new_count:=jsonb_array_length(coalesce(p_next->'current'->'entries','[]'::jsonb));
    if v_new_count<v_old_count or v_new_count>v_old_count+3
      or (v_old_count>0 and p_next->'current'->'entries'->(v_old_count-1) is distinct from v_old->'current'->'entries'->(v_old_count-1))
      then raise exception 'Unexpected turn data';end if;
  elsif p_action='correct' then
    -- Require the same live X01 stage, turn and visit count.
    if v_old->>'status'<>'playing' or p_next->>'status'<>'playing'
      or v_old->'current'->>'kind'<>'x01' or p_next->'current'->>'kind'<>'x01'
      or p_next->'stageIndex' is distinct from v_old->'stageIndex'
      or p_next->'summaries' is distinct from v_old->'summaries'
      or p_next->'total' is distinct from v_old->'total'
      or p_next->'current'->'turn' is distinct from v_old->'current'->'turn'
      or p_next->'current'->'starter' is distinct from v_old->'current'->'starter'
      or p_next->'current'->'start' is distinct from v_old->'current'->'start'
      or p_next->'current'->'used' is distinct from v_old->'current'->'used'
      or p_next->'current'->'pending' is distinct from v_old->'current'->'pending'
      or p_next->'current'->'done' is distinct from v_old->'current'->'done'
      or p_next->'current'->'win' is distinct from v_old->'current'->'win'
      then raise exception 'Pentathlon correction must preserve stage and turn order';end if;
    v_other_slot:=1-v_slot;
    if p_next->'current'->'remaining'->v_other_slot is distinct from v_old->'current'->'remaining'->v_other_slot
      or p_next->'current'->'pent'->v_other_slot is distinct from v_old->'current'->'pent'->v_other_slot
      or p_next->'current'->'visitCounts'->v_other_slot is distinct from v_old->'current'->'visitCounts'->v_other_slot
      then raise exception 'Cannot change opponent Pentathlon totals';end if;
    v_old_count:=jsonb_array_length(coalesce(v_old->'current'->'entries','[]'::jsonb));
    v_new_count:=jsonb_array_length(coalesce(p_next->'current'->'entries','[]'::jsonb));
    if v_old_count<1 or v_old_count<>v_new_count then raise exception 'Correction must preserve visit count';end if;
    for v_idx in 0..v_old_count-1 loop
      v_prev_entry:=v_old->'current'->'entries'->v_idx;
      v_next_entry:=p_next->'current'->'entries'->v_idx;
      if v_prev_entry->>'type' is distinct from v_next_entry->>'type'
        or v_prev_entry->'player' is distinct from v_next_entry->'player'
        or v_prev_entry->'darts' is distinct from v_next_entry->'darts'
        or v_prev_entry->'checkout' is distinct from v_next_entry->'checkout'
        then raise exception 'Correction cannot change visits or checkout';end if;
      if v_prev_entry->'attempt' is distinct from v_next_entry->'attempt' then
        v_changed:=v_changed+1;
        if v_changed<>1 or v_prev_entry->>'type'<>'visit'
          or (v_prev_entry->>'player')::integer<>v_slot
          or v_prev_entry->>'checkout'='true'
          or jsonb_typeof(v_next_entry->'attempt')<>'number'
          or (v_next_entry->>'attempt')::integer not between 0 and 180
          then raise exception 'Only own recent non-checkout X01 visit may change';end if;
        select count(*) into v_owned_later
          from jsonb_array_elements(v_old->'current'->'entries') with ordinality as e(entry,ord)
          where e.ord>v_idx+1 and e.entry->>'type'='visit'
            and (e.entry->>'player')::integer=v_slot;
        if v_owned_later>=3 then raise exception 'Only last three own visits may be corrected';end if;
      end if;
    end loop;
    if v_changed<>1 then raise exception 'Exactly one visit score must change';end if;
  elsif p_action='advance' then
    if v_old->>'status'<>'review'
       or (p_next->>'stageIndex')::integer<>(v_old->>'stageIndex')::integer+1
       or p_next->'summaries' is distinct from v_old->'summaries'
       or p_next->'total' is distinct from v_old->'total'
       then raise exception 'Cannot advance Pentathlon stage';end if;
  else
    if r.last_actor is distinct from v_user or v_old->>'status' not in ('playing','review')
       or jsonb_array_length(coalesce(v_old->'undo','[]'::jsonb))<>1
       or p_next-'undo' is distinct from (v_old->'undo'->0)-'undo'
       then raise exception 'Cannot undo another player''s turn';end if;
  end if;
  update public.pentathlon_room_tests set state=p_next,version=version+1,
    last_actor=case when p_action='advance' then null else v_user end,
    updated_at=now()
  where challenge_id=p_challenge_id returning * into r;
  if r.match_id is not null and p_next->>'status'='finished' then
    update public.matches
      set status='finished',finished_at=now(),updated_at=now(),
        winner_id=case
          when (p_next->'total'->>0)::integer>(p_next->'total'->>1)::integer then r.player1_id
          when (p_next->'total'->>1)::integer>(p_next->'total'->>0)::integer then r.player2_id
          else null end
      where id=r.match_id and game_variant='pentathlon' and status='playing';
    update public.profiles set status='unavailable'
      where id in(r.player1_id,r.player2_id);
  end if;
  return to_jsonb(r);
end;$function$
;

CREATE OR REPLACE FUNCTION public.correct_pentathlon_clock_dart(p_challenge_id uuid, p_expected_version bigint, p_entry_index integer, p_hit integer)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
DECLARE
 r public.pentathlon_room_tests%rowtype;
 v_user uuid:=auth.uid();
 v_slot integer;
 v_entries jsonb;
 v_item jsonb;
 v_i integer;
 v_count integer;
 v_owned_later integer:=0;
 v_player integer;
 v_j integer;
 v_hit text;
 v_target integer;
 v_old_target integer;
 v_bonus integer;
 v_extra integer;
 v_targets integer[]:=ARRAY[1,1];
 v_used integer[]:=ARRAY[0,0];
 v_pent integer[]:=ARRAY[0,0];
 v_done boolean[]:=ARRAY[false,false];
 v_state jsonb;
 v_current jsonb;
BEGIN
 IF v_user IS NULL THEN RAISE EXCEPTION 'Authentication required';END IF;
 IF p_hit NOT IN (0,2) OR p_entry_index IS NULL OR p_entry_index<0
 THEN RAISE EXCEPTION 'Invalid clock hit: choose 0 or 2';END IF;
 SELECT * INTO r FROM public.pentathlon_room_tests
 WHERE challenge_id=p_challenge_id FOR UPDATE;
 IF NOT FOUND OR v_user NOT IN (r.player1_id,r.player2_id)
 THEN RAISE EXCEPTION 'Pentathlon game not found';END IF;
 IF r.version<>p_expected_version THEN RAISE EXCEPTION 'PENTATHLON_STALE_VERSION';END IF;
 IF r.state->>'status'<>'playing'
 OR r.state->'current'->>'kind'<>'clock'
 OR (r.state->>'stageIndex')::integer<>5
 THEN RAISE EXCEPTION 'Klokka rundt is not active';END IF;
 IF r.match_id IS NOT NULL AND NOT EXISTS (
  SELECT 1 FROM public.matches
  WHERE id=r.match_id AND game_variant='pentathlon' AND status='playing'
 ) THEN RAISE EXCEPTION 'Pentathlon match is no longer active';END IF;
 v_slot:=CASE WHEN v_user=r.player1_id THEN 0 ELSE 1 END;
 v_entries:=r.state->'current'->'entries';
 v_count:=jsonb_array_length(v_entries);
 IF p_entry_index>=v_count THEN RAISE EXCEPTION 'Dart not found';END IF;
 v_item:=v_entries->p_entry_index;
 IF v_item->>'type'<>'dart' OR (v_item->>'player')::integer<>v_slot
 THEN RAISE EXCEPTION 'Only your own dart can be corrected';END IF;
 FOR v_i IN (p_entry_index+1)..(v_count-1) LOOP
   IF (v_entries->v_i->>'player')::integer=v_slot THEN
     v_owned_later:=v_owned_later+1;
   END IF;
 END LOOP;
 IF v_owned_later>=3 THEN
  RAISE EXCEPTION 'Only your last three darts can be corrected';END IF;
 v_old_target:=(substring(v_item->>'target' FROM '^D([1-9]|1[0-9]|20)$'))::integer;
 IF v_old_target IS NULL THEN RAISE EXCEPTION 'Invalid clock target';END IF;
 v_hit:=CASE WHEN p_hit=0 THEN 'BOM' ELSE 'D'||v_old_target::text END;
 IF v_item->>'hit'=v_hit THEN RETURN to_jsonb(r);END IF;
 v_entries:=jsonb_set(v_entries,ARRAY[p_entry_index::text,'hit'],to_jsonb(v_hit));
 FOR v_i IN 0..(v_count-1) LOOP
   v_item:=v_entries->v_i;
   IF v_item->>'type'<>'dart' THEN RAISE EXCEPTION 'Invalid clock visit';END IF;
   v_player:=(v_item->>'player')::integer;
   IF v_player NOT IN (0,1) THEN RAISE EXCEPTION 'Invalid player';END IF;
   v_j:=v_player+1;
   IF v_done[v_j] OR v_used[v_j]>=42 THEN
     RAISE EXCEPTION 'Correction would change game completion';END IF;
   v_target:=v_targets[v_j];
   IF v_target>20 THEN RAISE EXCEPTION 'Unexpected throw after D20';END IF;
   IF (v_item->>'dart')::integer<>v_used[v_j]+1 THEN
     RAISE EXCEPTION 'Invalid clock dart order';END IF;
   v_hit:=v_item->>'hit';
   IF v_hit<>'BOM'
      AND v_hit !~ '^D([1-9]|1[0-9]|20)$'
   THEN RAISE EXCEPTION 'Invalid clock hit';END IF;
   v_bonus:=0;
   v_item:=jsonb_set(v_item,'{target}',to_jsonb('D'||v_target::text));
   v_item:=v_item-'finishBonus';
   v_used[v_j]:=v_used[v_j]+1;
   IF v_hit='D'||v_target::text THEN
     v_bonus:=2;
     v_targets[v_j]:=v_target+1;
     IF v_targets[v_j]=21 THEN
       v_extra:=42-v_used[v_j];
       v_bonus:=v_bonus+v_extra;
       v_done[v_j]:=true;
       v_item:=jsonb_set(v_item,'{finishBonus}',to_jsonb(v_extra));
     END IF;
   END IF;
   IF v_used[v_j]=42 THEN v_done[v_j]:=true;END IF;
   v_pent[v_j]:=v_pent[v_j]+v_bonus;
   v_item:=jsonb_set(v_item,'{bonus}',to_jsonb(v_bonus));
   v_entries:=jsonb_set(v_entries,ARRAY[v_i::text],v_item);
 END LOOP;
 IF to_jsonb(v_used) IS DISTINCT FROM r.state->'current'->'used'
 OR to_jsonb(v_done) IS DISTINCT FROM r.state->'current'->'done'
 THEN RAISE EXCEPTION 'Correction would change stage completion';END IF;
 IF v_done[1] AND v_done[2] THEN RAISE EXCEPTION 'Stage is already complete';END IF;
 v_current:=r.state->'current';
 v_current:=jsonb_set(v_current,'{entries}',v_entries);
 v_current:=jsonb_set(v_current,'{pent}',to_jsonb(v_pent));
 v_current:=jsonb_set(v_current,'{clockTarget}',to_jsonb(v_targets));
 v_state:=jsonb_set(r.state,'{current}',v_current);
 v_state:=jsonb_set(v_state,'{undo}',jsonb_build_array(r.state-'undo'));
 UPDATE public.pentathlon_room_tests
 SET state=v_state,version=version+1,last_actor=v_user,updated_at=now()
 WHERE challenge_id=p_challenge_id RETURNING * INTO r;
 RETURN to_jsonb(r);
END;
$function$
;

CREATE OR REPLACE FUNCTION public.correct_pentathlon_shanghai_dart(p_challenge_id uuid, p_expected_version bigint, p_entry_index integer, p_multiplier integer)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
DECLARE
 r public.pentathlon_room_tests%rowtype;
 v_user uuid:=auth.uid();
 v_slot integer;
 v_entries jsonb;
 v_entry jsonb;
 v_n integer;
 v_i integer;
 v_own_later integer:=0;
 v_own_count integer:=0;
 v_target integer;
 v_mult integer;
 v_mask integer:=0;
 v_base integer;
 v_points integer:=0;
 v_bonus integer;
 v_hit text;
 v_state jsonb;
 v_current jsonb;
BEGIN
 IF v_user IS NULL THEN RAISE EXCEPTION 'Authentication required'; END IF;
 IF p_multiplier NOT BETWEEN 0 AND 3 OR p_entry_index < 0
 THEN RAISE EXCEPTION 'Invalid Shanghai correction'; END IF;
 SELECT * INTO r FROM public.pentathlon_room_tests
 WHERE challenge_id=p_challenge_id FOR UPDATE;
 IF NOT FOUND OR v_user NOT IN (r.player1_id,r.player2_id)
 THEN RAISE EXCEPTION 'Pentathlon test not found'; END IF;
 IF r.version<>p_expected_version THEN RAISE EXCEPTION 'PENTATHLON_STALE_VERSION'; END IF;
 IF r.state->>'status'<>'playing' OR r.state->'current'->>'kind'<>'shanghai'
   OR r.state->>'stageIndex'<>'4'
 THEN RAISE EXCEPTION 'Shanghai stage is not active'; END IF;
 IF r.match_id IS NOT NULL AND NOT EXISTS(
   SELECT 1 FROM public.matches WHERE id=r.match_id
   AND game_variant='pentathlon' AND status='playing'
 ) THEN RAISE EXCEPTION 'Pentathlon match is no longer active'; END IF;
 v_slot:=CASE WHEN v_user=r.player1_id THEN 0 ELSE 1 END;
 v_entries:=r.state->'current'->'entries';
 v_n:=jsonb_array_length(v_entries);
 IF p_entry_index>=v_n THEN RAISE EXCEPTION 'Dart not found'; END IF;
 v_entry:=v_entries->p_entry_index;
 IF v_entry->>'type'<>'dart' OR (v_entry->>'player')::integer<>v_slot
 THEN RAISE EXCEPTION 'You can only correct your own darts'; END IF;
 FOR v_i IN (p_entry_index+1)..(v_n-1) LOOP
   IF (v_entries->v_i->>'player')::integer=v_slot THEN
     v_own_later:=v_own_later+1;
   END IF;
 END LOOP;
 IF v_own_later>=3 THEN RAISE EXCEPTION 'Only your last three darts can be corrected'; END IF;
 v_target:=(substring(v_entry->>'target' FROM '^TALL ([1-9])$'))::integer;
 IF v_target IS NULL THEN RAISE EXCEPTION 'Invalid Shanghai target'; END IF;
 v_hit:=CASE p_multiplier WHEN 0 THEN 'BOM'
              WHEN 1 THEN 'S' || v_target::text
              WHEN 2 THEN 'D' || v_target::text
              ELSE 'T' || v_target::text END;
 IF v_hit=v_entry->>'hit' THEN RETURN to_jsonb(r); END IF;
 v_entry:=jsonb_set(v_entry,'{hit}',to_jsonb(v_hit));
 v_entries:=jsonb_set(v_entries,ARRAY[p_entry_index::text],v_entry);
 -- Recalculate every recorded Shanghai score for this player, including
 -- the six-point bonus for having S+D+T in a single 3-dart round.
 FOR v_i IN 0..v_n-1 LOOP
   v_entry:=v_entries->v_i;
   IF (v_entry->>'player')::integer<>v_slot THEN CONTINUE; END IF;
   IF v_entry->>'type'<>'dart' THEN RAISE EXCEPTION 'Invalid Shanghai entry'; END IF;
   v_target:=v_own_count/3+1;
   IF v_target NOT BETWEEN 1 AND 9 OR v_entry->>'target' IS DISTINCT FROM 'TALL ' || v_target::text
   THEN RAISE EXCEPTION 'Invalid Shanghai history'; END IF;
   v_hit:=v_entry->>'hit';
   IF v_hit='BOM' THEN v_mult:=0;
   ELSIF v_hit='S'||v_target::text THEN v_mult:=1;
   ELSIF v_hit='D'||v_target::text THEN v_mult:=2;
   ELSIF v_hit='T'||v_target::text THEN v_mult:=3;
   ELSE RAISE EXCEPTION 'Invalid Shanghai hit'; END IF;
   v_bonus:=v_mult;
   IF v_own_count%3=0 THEN v_mask:=0; END IF;
   IF v_mult>0 THEN v_mask:=v_mask | (1 << (v_mult-1)); END IF;
   v_own_count:=v_own_count+1;
   IF v_own_count%3=0 AND v_mask=7 THEN v_bonus:=v_bonus+6;
     v_entry:=jsonb_set(v_entry,'{shanghai}','true'::jsonb);
   ELSE v_entry:=v_entry-'shanghai'; END IF;
   v_entry:=jsonb_set(v_entry,'{bonus}',to_jsonb(v_bonus));
   v_entries:=jsonb_set(v_entries,ARRAY[v_i::text],v_entry);
   v_points:=v_points+v_bonus;
 END LOOP;
 v_current:=jsonb_set(r.state->'current','{entries}',v_entries);
 v_current:=jsonb_set(v_current,ARRAY['pent',v_slot::text],to_jsonb(v_points));
 v_state:=jsonb_set(r.state,'{current}',v_current);
 v_state:=jsonb_set(v_state,'{undo}',jsonb_build_array(r.state-'undo'));
 UPDATE public.pentathlon_room_tests
 SET state=v_state,version=version+1,last_actor=v_user,updated_at=now()
 WHERE challenge_id=p_challenge_id RETURNING * INTO r;
 RETURN to_jsonb(r);
END;
$function$
;

CREATE OR REPLACE FUNCTION public.start_pentathlon_match_test(p_match_id uuid, p_challenge_id uuid, p_state jsonb)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare m public.matches%rowtype;c public.challenges%rowtype;r public.pentathlon_room_tests%rowtype;
begin
 if auth.uid() is null then raise exception 'Authentication required';end if;
 select * into m from public.matches where id=p_match_id;
 select * into c from public.challenges where id=p_challenge_id for update;
 if m.id is null or m.game_variant<>'pentathlon' or m.status<>'playing'
  or c.id is null or c.status<>'accepted'
  or m.player1_id<>c.challenger_id or m.player2_id<>c.challenged_id
  or m.created_at<c.created_at or auth.uid() not in(m.player1_id,m.player2_id)
 then raise exception 'Valid Pentathlon match required';end if;
 if jsonb_typeof(p_state)<>'object' or p_state->>'status'<>'playing'
  or p_state->>'stageIndex'<>'0' or p_state->>'version'<>'1'
  or p_state->'current'->>'kind'<>'x01'
  or p_state->'current'->'entries'<>'[]'::jsonb
  or jsonb_array_length(coalesce(p_state->'players','[]'::jsonb))<>2
  or ((p_state->>'firstStarter')::int=0 and m.match_starter_id<>m.player1_id)
  or ((p_state->>'firstStarter')::int=1 and m.match_starter_id<>m.player2_id)
  or p_state->'current'->'turn'<>p_state->'firstStarter'
  or p_state->'current'->'remaining'<>'[501, 501]'::jsonb
  or p_state->'current'->'used'<>'[0, 0]'::jsonb
  or p_state->'total'<>'[0, 0]'::jsonb
  or p_state->'summaries'<>'[]'::jsonb
  or octet_length(p_state::text)>150000
  then raise exception 'Invalid Pentathlon initial state';end if;
 insert into public.pentathlon_room_tests(challenge_id,match_id,player1_id,player2_id,state)
 values(p_challenge_id,p_match_id,m.player1_id,m.player2_id,p_state)
 on conflict(challenge_id) do nothing;
 select * into r from public.pentathlon_room_tests where challenge_id=p_challenge_id;
 if r.match_id is null and r.state->>'status'='playing'
     and r.state->>'stageIndex'='0'
     and r.state->'current'->'entries'='[]'::jsonb
     and r.state->'current'->'used'='[0, 0]'::jsonb
     and r.version<=1
   then
     update public.pentathlon_room_tests
       set match_id=p_match_id,state=p_state,version=version+1,updated_at=now()
       where challenge_id=p_challenge_id returning * into r;
   end if;
   if r.match_id is distinct from p_match_id then
     raise exception 'An existing Pentathlon test has throws. Create a new challenge for the match';
   end if;
 return to_jsonb(r);
end;$function$
;

