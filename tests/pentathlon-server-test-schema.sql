create role anon;create role authenticated;
create schema auth;
create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('test.actor',true),'')::uuid$$;
create table public.pentathlon_room_tests(id int generated by default as identity (start with 2) primary key, challenge_id uuid unique, updated_at timestamptz default now(), created_at timestamptz default now(), match_id uuid, player1_id uuid not null, player2_id uuid not null, state jsonb not null, version bigint not null default 1, last_actor uuid);

-- Synthetic fixture tables and production RPC definitions; no production data.
create table public.matches(id uuid primary key, game_variant text, status text, player1_id uuid, player2_id uuid, match_starter_id uuid, created_at timestamptz, updated_at timestamptz, finished_at timestamptz, winner_id uuid);
create table public.challenges(id uuid primary key, status text, challenger_id uuid, challenged_id uuid, created_at timestamptz);
create table public.profiles(id uuid primary key, status text);
