  add column if not exists result_source text not null default 'solo',
  add column if not exists match_id uuid references public.matches(id) on delete set null;

alter table public.jdc_challenge_results drop constraint if exists jdc_challenge_results_result_source_check;
alter table public.jdc_challenge_results add constraint jdc_challenge_results_result_source_check
  check (result_source in ('solo','online'));

create unique index if not exists jdc_challenge_results_online_match_player_uq
  on public.jdc_challenge_results(match_id,user_id)
  where result_source='online' and match_id is not null;

drop view if exists public.jdc_challenge_best;
create view public.jdc_challenge_best with (security_invoker=true) as
select distinct on (r.user_id)
  r.user_id,p.username,r.score as best_score,r.phase1_score,r.doubles_score,r.phase3_score,
  r.doubles_hit,r.shanghai_count,r.badge,r.created_at as achieved_at,r.id as result_id
from public.jdc_challenge_results r
join public.profiles p on p.id=r.user_id
where r.result_source='online'
order by r.user_id,r.score desc,r.created_at asc;
revoke all on public.jdc_challenge_best from anon;
grant select on public.jdc_challenge_best to authenticated;

