create table if not exists public.jdc_match_turns(
  id bigint generated by default as identity primary key,
  match_id uuid not null references public.matches(id) on delete cascade,
  player_id uuid not null references public.profiles(id) on delete cascade,
  turn_no smallint not null check(turn_no between 1 and 33),
  hits jsonb not null,
  points integer not null check(points between 0 and 280),
  shanghai_bonus boolean not null default false,
  created_at timestamptz not null default now(),
  unique(match_id,player_id,turn_no)
);
alter table public.jdc_match_turns enable row level security;
drop policy if exists "JDC match participants can read turns" on public.jdc_match_turns;
